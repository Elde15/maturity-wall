"""Gate 4 evidence: docs/qa/gate4_underwriting.md, generated from the engine's outputs."""
from __future__ import annotations

import math

import numpy as np
import pandas as pd

from mwall.clean.qa_report import md_table
from mwall.common import paths
from mwall.underwrite import handcheck

DOC = paths.REPO_ROOT / "docs" / "qa" / "gate4_underwriting.md"
ORDER = ["office", "retail", "industrial", "multifamily", "self_storage", "lodging", "mixed_use", "other"]


def _bn(x: float) -> str:
    return f"{x / 1e9:,.1f}"


def _pct(x: float) -> str:
    return "" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{100 * x:.1f}%"


def by_type(x: pd.DataFrame) -> pd.DataFrame:
    g = x.groupby("property_group")
    t = pd.DataFrame({
        "loans valued": g["value"].count(),
        "balance ($bn)": g["wl_balance_est"].sum() / 1e9,
        "with a gap": g["refi_gap_pct"].apply(lambda s: int((s > 0).sum())),
        "gap ($bn)": g["refi_gap"].sum() / 1e9,
        "median cap rate": g["cap_rate"].median().map(_pct),
        "return bid / value bid (median)": (x["return_bid"] / x["value_bid"]).groupby(x["property_group"]).median(),
        "bid below balance": g["refinanceable_by_sale"].apply(lambda s: int((s == False).sum())),  # noqa: E712
    }).reindex(ORDER)
    return t.reset_index().rename(columns={"property_group": "type"})


def write(out: pd.DataFrame, grid: pd.DataFrame, mono: pd.DataFrame, rows: list[dict], P: dict, M: dict,
          log=print) -> None:
    base = out[out["scenario"].eq("base")]
    L = pd.DataFrame(rows)
    lines = ["# Gate 4 evidence: underwriting engine", "",
             "Generated by `python -m mwall underwrite` from `data/outputs/underwriting.parquet`. Method: "
             "`docs/underwriting.md`. Parameters: `config/underwriting_params.csv`, `config/la_overrides.csv`, "
             "`config/lender_params.csv`, `config/scenarios.csv`.", ""]

    lines += ["## Market inputs on the valuation date", "",
              f"Valuation date {M['date']}. Treasury yields of {M['treasury_date']}: 10-year {M['ust10']:.2%}, "
              f"5-year {M['ust5']:.2%}. CBRE lending spread over the 10-year ({M['spread_quarter']['commercial']}, "
              f"published {M['spread_publication']['commercial']}): commercial {M['spread_bps']['commercial']:.0f} bp, "
              f"multifamily {M['spread_bps']['multifamily']:.0f} bp.", ""]
    bench = L.dropna(subset=["group"]).groupby("group")[["bench_today"]].median().reindex(ORDER)
    bench["benchmark"] = L.dropna(subset=["group"]).groupby("group")["bench_kind"].agg(
        lambda s: s.mode().iat[0]).reindex(ORDER)
    bench["bench_today"] = bench["bench_today"].map(_pct)
    lines += [md_table(bench.reset_index().rename(columns={"group": "type", "bench_today": "cap-rate benchmark today"})),
              "", "The composite benchmark is the mean of the office, retail, industrial and multifamily series, "
              "used for types with no current series of their own.", ""]

    lines += ["## Coverage and confidence tiers", ""]
    tiers = L.assign(tier=L["tier"].fillna("none")).groupby(["tier"]).size().rename("loans").reset_index()
    lines += [md_table(tiers), "", "Why a loan has no tier or dropped a tier:", ""]
    why = L.loc[L["tier_reason"].ne(""), "tier_reason"].value_counts().rename("loans").reset_index()
    lines += [md_table(why.rename(columns={"tier_reason": "reason"})), ""]
    src = L.loc[L["tier"].notna(), "noi_source"].fillna("").str.startswith("filing of").mean()
    lines += [f"{_pct(src)} of underwritten loans take their NOI from an earlier filing because the latest one left "
              "the financial fields blank.", ""]

    lines += ["## Scenarios", ""]
    sc = out.groupby("scenario").agg(
        valued=("value", "count"), gap_bn=("refi_gap", "sum"), with_gap=("refi_gap_pct", lambda s: int((s > 0).sum())),
        return_bids=("return_bid", "count"), bid_below_balance=("refinanceable_by_sale", lambda s: int((s == False).sum())),  # noqa: E712
        median_discount_when_below=("discount", lambda s: s[s > 0].median()))
    sc["gap_bn"] = sc["gap_bn"].map(_bn)
    sc["median_discount_when_below"] = sc["median_discount_when_below"].map(_pct)
    lines += [md_table(sc.reset_index().rename(columns={
        "gap_bn": "refinance gap ($bn)", "with_gap": "loans with a gap", "return_bids": "loans with a return bid",
        "bid_below_balance": "bid below balance", "median_discount_when_below": "median discount where below"})), ""]
    for name in ("base", "downside"):
        lines += [f"### {name.capitalize()} scenario by property type", "",
                  md_table(by_type(out[out["scenario"].eq(name)])), ""]
    rb = base.dropna(subset=["return_bid"])
    lines += [f"At the 20% levered hurdle the return bid is below the value bid for "
              f"{_pct((rb['return_bid'] < rb['value_bid']).mean())} of loans with a cash-flow model; a buyer paying "
              f"market value would not reach the hurdle. Paying the value bid, the median unlevered IRR is "
              f"{_pct(rb['irr_unlevered_at_value_bid'].median())} and the median levered IRR "
              f"{_pct(rb['irr_at_value_bid'].median())}: bridge debt at the 5-year Treasury plus 300 to 425 bp "
              f"costs more than the property yields, so leverage lowers the return (negative leverage).", ""]

    lines += ["## Sensitivity (base scenario)", "", "Total refinance gap, $bn, as the refinance rate and cap rates move "
              "(rows: rate shift in bp; columns: cap-rate shift in bp):", ""]
    piv = grid.pivot_table(index="rate_shift_bps", columns="cap_shift_bps", values="refi_gap", aggfunc="sum") / 1e9
    piv.columns = [f"cap {c:+d}" for c in piv.columns]
    lines += [md_table(piv.reset_index().rename(columns={"rate_shift_bps": "rate shift"}), floatfmt=".1f"), "",
              "Median return bid as a share of the base return bid:", ""]
    b0 = grid[(grid["rate_shift_bps"] == 0) & (grid["cap_shift_bps"] == 0)].set_index("whole_loan_id")["return_bid"]
    rel = grid.assign(rel=grid["return_bid"] / grid["whole_loan_id"].map(b0))
    p2 = rel.pivot_table(index="rate_shift_bps", columns="cap_shift_bps", values="rel", aggfunc="median")
    p2.columns = [f"cap {c:+d}" for c in p2.columns]
    lines += [md_table(p2.reset_index().rename(columns={"rate_shift_bps": "rate shift"}), floatfmt=".3f"), "",
              "Direction checks on every loan and every step of the grid (SOP 15: higher rates widen gaps and lower "
              "bids; higher cap rates lower value):", "", md_table(mono), "",
              "A step that holds flat is a loan the constraint doesn't touch: a gap of zero that stays zero, or a cap "
              "rate held at the 3.5% floor when cap rates fall 100 bp.", ""]

    lines += ["## Edge cases (SOP 15, Gate 4)", ""]
    vb_neg = int((base["value_bid"] <= 0).sum())
    floor_hits = int((base["cap_rate"] <= 0.035 + 1e-12).sum())
    lines += [md_table(pd.DataFrame([
        ("zero or missing NOI", f"{int(L['tier_reason'].eq('no current NOI').sum()):,} loans with no NOI and "
         f"{int(L['tier_reason'].str.contains('older than 36').sum()):,} with NOI over 36 months old are not "
         "underwritten (no value, no bid); their refinance gap is left blank"),
        ("negative NOI", f"{int(L['tier_reason'].eq('NOI zero or negative').sum()):,} loans: no value or bid; the "
         "refinance gap is the whole balance because no lender sizes a loan on negative income"),
        ("bid above balance", f"{int(base['refinanceable_by_sale'].eq(True).sum()):,} loans are flagged refinanceable "
         "by sale and shown with no discount"),
        ("multi-property loans", f"{int(L['jurisdiction'].eq('multi_property').sum()):,} loans: valued on the "
         "pooled NOI; listed tenants (which describe only the largest property) and local tax and rent rules are "
         "not applied; rollover uses the even-turnover assumption on the whole area"),
        ("partial-year financials", f"annualized at cleaning (D021); "
         f"{int(L['tier_reason'].str.contains('under 6 months').sum()):,} loans annualized from under six months "
         "drop one tier"),
        ("lease-up larger than value", f"{vb_neg:,} loans have a value bid at or below zero and a bid of zero"),
        ("cap-rate floor", f"{floor_hits:,} loans at the 3.5% floor in the base scenario"),
        ("clipped securitization spread", f"{int(L['spread_clipped'].sum()):,} loans had their spread held to the "
         "10th-90th percentile of their type"),
    ], columns=["case", "handling"])), ""]

    lines += ["## Los Angeles and Orange County rules", ""]
    j = L["jurisdiction"].value_counts().rename("loans").reset_index()
    lines += [md_table(j), "", f"Proposition 13 tax reset applied to {int(L['tax_current'].notna().sum()):,} loans; "
              f"rent caps on {int(np.isfinite(L['rent_cap']).sum()):,} multifamily loans "
              f"({int((L['rent_cap'] < 0.05).sum()):,} under the City rent ordinance or the County's)."]
    la = base[base["jurisdiction"].eq("la_city")]
    if len(la):
        # exit cost = the 2% selling cost plus ULA (5.5% or 4%)
        lines += [f" Measure ULA at exit: {int((la['exit_cost_rate'] >= 0.0749).sum())} City of Los Angeles loans at "
                  f"the 5.5% rate, {int(((la['exit_cost_rate'] > 0.059) & (la['exit_cost_rate'] < 0.0749)).sum())} at 4%."]
    lines += [""]

    lines += ["## Opportunity score (base scenario, top 15)", "",
              "Rank-average of failure or distress probability, refinance gap, implied discount, the levered IRR at "
              "the value bid, confidence tier and balance (`underwrite/run.py: opportunity`).", ""]
    top = base.nlargest(15, "opportunity_score")[["whole_loan_id", "property_group", "status", "wl_balance_est",
                                                 "refi_gap_pct", "discount", "tier", "opportunity_score"]].copy()
    top["wl_balance_est"] = (top["wl_balance_est"] / 1e6).round(1)
    top["refi_gap_pct"] = top["refi_gap_pct"].map(_pct)
    top["discount"] = top["discount"].map(_pct)
    lines += [md_table(top.rename(columns={"wl_balance_est": "balance ($m)", "refi_gap_pct": "gap",
                                           "opportunity_score": "score"}), floatfmt=".1f"), ""]

    lines += ["## Hand check", "", "Three loans rebuilt in `docs/qa/handcheck/underwriting_handcheck.xlsx`, every "
              "step an Excel formula recalculated by Excel; `tests/test_underwrite.py` requires the engine to match "
              "it to the cent (NOI path, loan sizing, values, bids, cash flows) and the IRRs to 1e-7.", ""]
    if handcheck.BOOK.exists():
        book = handcheck.read()
        hc = []
        for case, scen in handcheck.CASES:
            v = book[case]
            hc.append({"case": case, "loan": v["whole_loan_id"], "scenario": scen, "NOI year 1": f"{v['noi_y1']:,.2f}",
                       "max new loan": f"{v['p_max']:,.2f}", "value bid": f"{v['value_bid']:,.2f}",
                       "return bid": f"{v['return_bid']:,.2f}", "levered IRR": f"{v['irr_levered']:.6f}",
                       "unlevered IRR": f"{v['irr_unlevered']:.6f}"})
        lines += [md_table(pd.DataFrame(hc)), ""]
    DOC.write_text("\n".join(lines) + "\n", encoding="utf-8")
    log(f"report -> {DOC.relative_to(paths.REPO_ROOT)}")
